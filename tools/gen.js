function pairs(pool, count, maxOff) {
  const res = [], seen = {}, n = pool.length;
  maxOff = maxOff || n;
  for (let off = 1; off < maxOff && res.length < count; off++) {
    for (let i = 0; i < n && res.length < count; i++) {
      const j = (i + off) % n;
      if (i === j) continue;
      const key = i < j ? i + "-" + j : j + "-" + i;
      if (seen[key]) continue;
      seen[key] = 1;
      res.push([pool[i], pool[j]]);
    }
  }
  return res;
}

